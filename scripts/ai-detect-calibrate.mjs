function show(name, r) {
  if (!r.ok) {
    console.log(`${name}: ❌ ${r.reason} (${r.wordCount} كلمة)`);
    return;
  }
  const sigs = r.signals
    .filter((s) => s.score > 15)
    .map((s) => `${s.id}:${s.score}`)
    .join(' ');
  console.log(
    `${name}: ${r.percent}%  [${r.verdict}]  offset-${r.humanOffset}  {${sigs}}`
  );
  console.log(`   عبارات: ${r.phrases.slice(0, 6).map((p) => `${p.phrase}×${p.count}`).join(' | ') || '—'}`);
  if (r.humanMarks.length)
    console.log(`   بشرية: ${r.humanMarks.map((p) => `${p.phrase}×${p.count}`).join(' | ')}`);
}

const paper2 = readFileSync('/home/z/my-project/.tmp-perf/paper2.txt', 'utf8');

show('AI خام      ', analyzeAiText(AI_RAW));
