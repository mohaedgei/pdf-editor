const r4 = analyzeAiText(HUMAN_FORMAL);
if (r1.ok) targets.push(['AI خام ≥ 75', r1.percent >= 75]);
if (rS.ok) targets.push(['AI متنكر ≥ 35', rS.percent >= 35]);
if (r2.ok) targets.push(['بحث الخصائص ≤ 55', r2.percent <= 55]);
if (r3.ok) targets.push(['عامية ≤ 25', r3.percent <= 25]);
if (r4.ok) targets.push(['خبر بشري ≤ 45', r4.percent <= 45]);
console.log('\n--- الفحص ---');
let pass = true;
for (const [label, ok] of targets) {
  console.log(`${ok ? '✅' : '❌'} ${label}`);
  if (!ok) pass = false;
}
process.exit(pass ? 0 : 1);
